from generator import generate_sas
from prompt_builder import build_prompt

def clean(code):
    """Remove markdown fences if the model added them anyway."""
    return code.replace("```sas", "").replace("```", "").strip()

def gen_block(row):
    """Generate one variable's derivation logic via the model."""
    print("Generating:", row["Variable"])
    return clean(generate_sas(build_prompt(row)))

def assemble_adsl(spec, derived, ex_summary, main_step):
    parts = []

    # ---- Header
    parts.append("/**********************************/")
    parts.append("/* Program: adsl.sas              */")
    parts.append("/* Generated by sas-program-generator */")
    parts.append("/**********************************/")
    parts.append("")

    # ---- Pre-step: collapse EX to one row per subject
    parts.append("/* Pre-step: summarize EX to one row per subject */")
    parts.append("proc sql;")
    parts.append("  create table ex_summary as select")
    parts.append("    usubjid,")
    parts.append("    min(case when exdose > 0 and exstdtc ne '' ")
    parts.append("        then datepart(input(exstdtc, e8601dt.)) end) as TRTSDT format=date9.,")
    parts.append("    max(case when exdose > 0 and exendtc ne '' ")
    parts.append("        then datepart(input(exendtc, e8601dt.)) end) as TRTEDT format=date9.")
    parts.append("  from ex")
    parts.append("  group by usubjid;")
    parts.append("quit;")
    parts.append("")

    # ---- Main step
    parts.append("data adsl;")
    parts.append("  merge dm ex_summary;")
    parts.append("  by usubjid;")
    parts.append("")

    # main-step derived variables, in spec Order
    for i, row in main_step.sort_values("Order").iterrows():
        parts.append(gen_block(row))
        parts.append("")

    # keep only spec variables
    keep_list = " ".join(spec["Variable"])
    parts.append("  keep " + keep_list + ";")
    parts.append("run;")

    return "\n".join(parts)